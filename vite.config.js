import { defineConfig } from 'vite'
import react from '@vitejs/plugin-react'
import { VitePWA } from 'vite-plugin-pwa'

export default defineConfig({
  plugins: [
    react(),

    // ── PWA + Workbox caching ─────────────────────────────────────────────
    // Generates a service worker that caches JS/CSS/HTML assets.
    // On repeat visits, assets load from cache (instant) instead of network.
    // Strategy: StaleWhileRevalidate — serve cache immediately, update in background.
    VitePWA({
      registerType: 'autoUpdate',
      includeAssets: ['favicon.ico', '*.svg', '*.png'],
      manifest: {
        name: 'Shadow System',
        short_name: 'ShadowSys',
        description: 'Solo Leveling Hunter Interface — track quests, rank up, build your shadow army.',
        theme_color: '#020408',
        background_color: '#020408',
        display: 'standalone',
        icons: [
          // 192x192: required by Chrome for the install prompt on Android
          { src: 'pwa-192x192.png', sizes: '192x192', type: 'image/png' },
          // 512x512: used on splash screens and high-DPI Android displays
          // 'any maskable' lets Android adaptive icons crop/reshape it safely
          { src: 'pwa-512x512.png', sizes: '512x512', type: 'image/png', purpose: 'any maskable' },
        ]
      },
      workbox: {
        // Cache all JS, CSS, and HTML chunks generated by Vite
        globPatterns: ['**/*.{js,css,html,woff,woff2}'],
        // StaleWhileRevalidate: serve from cache immediately, fetch update in background
        runtimeCaching: [
          {
            // Google Fonts stylesheets
            urlPattern: /^https:\/\/fonts\.googleapis\.com\/.*/i,
            handler: 'StaleWhileRevalidate',
            options: {
              cacheName: 'google-fonts-stylesheets',
              expiration: { maxEntries: 10, maxAgeSeconds: 60 * 60 * 24 * 365 }, // 1 year
            },
          },
          {
            // Google Fonts files (woff2)
            urlPattern: /^https:\/\/fonts\.gstatic\.com\/.*/i,
            handler: 'CacheFirst',
            options: {
              cacheName: 'google-fonts-webfonts',
              expiration: { maxEntries: 20, maxAgeSeconds: 60 * 60 * 24 * 365 }, // 1 year
              cacheableResponse: { statuses: [0, 200] },
            },
          },
          {
            // Firebase Auth & Firestore API calls — NetworkFirst (always try live data)
            urlPattern: /^https:\/\/(identitytoolkit|securetoken|firestore)\.googleapis\.com\/.*/i,
            handler: 'NetworkFirst',
            options: {
              cacheName: 'firebase-api',
              expiration: { maxEntries: 50, maxAgeSeconds: 60 * 5 }, // 5 min fallback
              networkTimeoutSeconds: 10,
            },
          },
        ],
      },
    }),


  ],

  build: {
    sourcemap: false,
    // ── Target modern browsers — eliminates legacy polyfill bloat (~30KB) ──
    target: 'es2020',
    rollupOptions: {
      output: {
        // ── Granular chunk splitting ──────────────────────────────────────
        // The old monolith: firebase(475KB) + vendor(270KB) = 750KB on first load.
        // The new approach: each chunk is independently cacheable. Crucially,
        // firebase-firestore (242KB) is NEVER downloaded by unauthenticated
        // visitors — it lazy-loads only after the user logs in via GameApp.
        manualChunks(id) {
          // React core — tiny, always needed, cached forever
          if (id.includes('node_modules/react/') || id.includes('node_modules/react-dom/')) {
            return 'react-core';
          }
          // Framer Motion — heavy (126KB), only used inside GameApp (post-login)
          if (id.includes('node_modules/framer-motion')) {
            return 'framer-motion';
          }
          // Firebase Auth — needed on the login screen
          if (id.includes('node_modules/firebase/auth') || id.includes('node_modules/@firebase/auth')) {
            return 'firebase-auth';
          }
          // Firebase Firestore — 242KB, deferred until AFTER user logs in
          if (id.includes('node_modules/firebase/firestore') || id.includes('node_modules/@firebase/firestore')) {
            return 'firebase-firestore';
          }
          // Firebase app core — shared tiny base
          if (id.includes('node_modules/firebase/app') || id.includes('node_modules/@firebase/app')) {
            return 'firebase-core';
          }
          // Remaining Firebase internals (util, component, logger, etc.)
          if (id.includes('node_modules/firebase') || id.includes('node_modules/@firebase')) {
            return 'firebase-misc';
          }
          // Zustand — tiny state manager
          if (id.includes('node_modules/zustand')) {
            return 'state';
          }
          // Google OAuth + jwt-decode — only needed on auth screen
          if (id.includes('node_modules/@react-oauth') || id.includes('node_modules/jwt-decode')) {
            return 'google-oauth';
          }
        }
      }
    }
  },

  // ── Dev proxy: routes /api/openrouter → openrouter.ai server-side ──
  // Bypasses ad blockers & CORS since the HTTP call is made by Node, not the browser
  server: {
    proxy: {
      '/api/openrouter': {
        target: 'https://openrouter.ai/api/v1',
        changeOrigin: true,
        rewrite: (path) => path.replace(/^\/api\/openrouter/, ''),
        secure: true,
      }
    }
  }
})

